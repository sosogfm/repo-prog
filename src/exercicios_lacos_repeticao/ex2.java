package exercicios_lacos_repeticao;

public class ex2 {

	public static void main(String[] args) {
		// Contagem regressiva (while) Escreva um programa que imprima uma contagem regressiva de 10 até 1 utilizando a estrutura while.

		int i = 10; 

        while (i >= 1) { 
            System.out.println(i);
            i--; // Decrementa 1 a cada volta
        }


	}

}
